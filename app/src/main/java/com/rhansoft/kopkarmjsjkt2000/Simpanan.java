package com.rhansoft.kopkarmjsjkt2000;

public class Simpanan {
    private String nmAnggota, kdAnggota, jnsSimpanan, namaSimpanan;
    private String totalSimpanan;

    public String getNamaAnggota() { return nmAnggota; }

    public void setNamaAnggota(String nmAnggota) { this.nmAnggota = nmAnggota; }

    public String getKdAnggota() {
        return kdAnggota;
    }

    public void setKdAnggota(String kdAnggota) {
        this.kdAnggota = kdAnggota;
    }

    public String getJnsSimpanan() {
        return jnsSimpanan;
    }

    public void setJnsSimpanan(String jnsSimpanan) {
        this.jnsSimpanan = jnsSimpanan;
    }

    public String getNamaSimpanan() {
        return namaSimpanan;
    }

    public void setNamaSimpanan(String namaSimpanan) {
        this.namaSimpanan = namaSimpanan;
    }

    public String getTotalSimpanan() {
        return totalSimpanan;
    }

    public void setTotalSimpanan(String totalSimpanan) {
        this.totalSimpanan = totalSimpanan;
    }
}
