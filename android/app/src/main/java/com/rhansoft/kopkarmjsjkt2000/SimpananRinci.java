package com.rhansoft.kopkarmjsjkt2000;

public class SimpananRinci {
    private String tglSimpanan, noReff, debit, kredit;

    public String getTglSimpanan() {
        return tglSimpanan;
    }

    public void setTglSimpanan(String tglSimpanan) {
        this.tglSimpanan = tglSimpanan;
    }

    public String getNoReff() {
        return noReff;
    }

    public void setNoReff(String noReff) {
        this.noReff = noReff;
    }

    public String getDebit() {
        return debit;
    }

    public void setDebit(String debit) {
        this.debit = debit;
    }

    public String getKredit() {
        return kredit;
    }

    public void setKredit(String kredit) {
        this.kredit = kredit;
    }
}
